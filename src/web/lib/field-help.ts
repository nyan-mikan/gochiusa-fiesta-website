export function fieldHelp(name:string,control:HTMLInputElement|HTMLTextAreaElement|HTMLSelectElement|null){
 const rules:[RegExp,string][]=[
 [/节目名|段落标题|小标题/,'填写作品或段落的名称，使用能直接识别内容的标题。'],
 [/^年份$/,'选择活动举办年份。点击候选入口展开年份表，输入时匹配；也可直接输入 2000–2200 之间的整数。'],
 [/^时区$/,'选择活动使用的时区。征稿时间按所选时区显示和填写。'],
 [/节目类型/,'选择作品实际所属类型。选「其他」时，还需填写具体类型。'],
 [/^分区名称$/,'填写管理员维护的分区名称，不可与已有分区重名。修改会检查版本，历史投稿引用保留。'],
 [/平台分区 ID/,'填写 B站平台对应分区的标识；尚未核实时可以留空。'],
 [/^职务标签/,'每行填写一个制作职务，不可重复。保存建立新字典版本，旧版本和历史投稿引用保留。'],
 [/分区/,'选择作品拟投稿的 B站分区。制作职务随分区变化；选「其他」时需说明具体分区。'],
 [/制作职务|职务标签|具体职务/,'使用当前分区的职务。没有合适选项时选「其他」并说明工作；管理员在「分区与职务」模块维护选项，旧投稿保留原版本。'],
 [/UID/,'填写 B站账号的非零数字 UID，不是昵称。同一 UID 不可重复，名称需保持一致，可通过空间链接核对。'],
 [/B站名称|署名/,'填写希望展示的名称。祝福语默认使用账号昵称，可在提交前修改；提交后署名固定。'],
 [/负责人/,'每份投稿选择一位负责人，负责接收和处理沟通。可与主投稿账号为同一人，再次点击可以取消。'],
 [/主投稿/,'选择实际在 B站发布作品的账号，每份投稿只能选择一人。'],
 [/参与制作|分工/,'勾选实际参与制作的成员，并填写对应职务；分工说明可补充具体负责的内容。'],
 [/祝福语/,'填写 1–2000 字的文本，不能只提交语音。每个账号在同一活动只能提交一则，提交后内容固定。'],
 [/简介/,'介绍作品内容和呈现方式，方便审核人员了解节目。'],
 [/预览链接|交付链接/,'填写可访问的 HTTPS 作品链接。上传文件或提供链接至少选择一种；有提取码时另填访问说明。'],
 [/时长|时 : 分 : 秒/,'填写节目实际播放时长（时、分、秒），正式投稿时不能为零。视频上传后会尝试读取时长，请核对。'],
 [/访问说明|提取码/,'填写审核人员访问作品所需的提取码或权限说明。不要填写账号密码。'],
 [/私钥/,'只接受本站下载的 JSON 私钥文件，最大 4 KiB。私钥在本机读取，服务器仅接收签名。遗失后可通过邮箱验证重新生成。'],
 [/上传作品/,'每次选择或拖入一个作品文件，最大 1 GB。等待上传完成后再提交。'],
 [/音频/,'管理员可附加不超过 20 MiB 的音频，支持 MP3、WAV、M4A、OGG、FLAC、WebM；祝福语文字仍然必填。'],
 [/用户昵称/,'最多 40 字，不能包含换行或控制字符；留空时显示邮箱前缀。更改昵称不会改写已提交的署名。'],
 [/验证码/,'输入发送到当前邮箱的六位验证码，十分钟内有效，只能使用一次。登录与领取私钥需要各自的验证码。'],
 [/邮箱/,'填写完整邮箱地址。验证码和投稿反馈会发送到这个邮箱。'],
 [/权限|模块/,'只有超级管理员可以分配管理模块。权限以服务器记录为准；变更后原登录会话失效，需重新登录。'],
 [/核实证据/,'填写 HTTPS 来源链接，便于核对 B站当前可选标签和人数上限。不要将尚未核实的资料标记为已核实。'],
 [/人员上限/,'填写该分区已核实的制作人员上限；未确认时留空，不根据猜测限制名单。'],
 [/征稿开始|征稿结束|日期|时间|时区/,'按照显示的活动时区填写，结束时间必须晚于开始时间。'],
 [/原因|审核意见/,'填写具体原因，便于投稿者或其他管理员处理；修改会保留审计记录。'],
 [/角色|应援色/,'通过角色管理维护名称、颜色和可见状态。归档保留历史引用，不删除已保存的台词。'],
 [/搜索|查找/,'输入名称或页面说明中的关键词筛选资料，不会修改已有记录。'],
 [/备注|补充说明/,'填写需要向审核或协作人员补充说明的事项，可留空。'],
 [/活动/,'选择或维护对应活动。资料和投稿按活动隔离，切换前请保存当前修改。'],
 [/台词|片段|舞台提示/,'台词 Enter 新建下一句，Ctrl / ⌘ + Enter 换行。分段台词可以选择多人合说；修改会检查版本。'],
 ];
 const result=[rules.find(([rule])=>rule.test(name))?.[1]??(control?.getAttribute('placeholder')||'此字段没有预设候选值，可直接输入。')];
 if(control?.required)result.push('此项必填。');
 if(control instanceof HTMLInputElement||control instanceof HTMLTextAreaElement){if(control.maxLength>0)result.push(`最多 ${control.maxLength} 字符。`);if(control.type==='number')result.push(`数值范围：${control.getAttribute('min')||'不限'} 至 ${control.getAttribute('max')||'不限'}。`);}
 if(control instanceof HTMLSelectElement)result.push('输入关键词匹配候选项，选择后回填。F1 / F4 展开候选表；取消不会改变当前值。');
 if((control instanceof HTMLInputElement||control instanceof HTMLTextAreaElement)&&control.readOnly)result.push('当前资料为只读。');
 return result;
}
